using BenchmarkDotNet.Toolchains;
using BenchmarkDotNet.Toolchains.Results;
using JetBrains.Annotations;

namespace BenchmarkDotNet.Tests
{
    public class BuildResultTests
    {
        [Fact]
        public void NotFullyCompatibleMsBuildErrorIsTranslatedToMoreUserFriendlyVersion()
        {
            const string msbuildError = @"C:\Program Files\dotnet\sdk\3.0.100-preview9-013617\Microsoft.Common.CurrentVersion.targets(1653,5): warning NU1702: ProjectReference 'C:\Projects\BenchmarkDotNet\tests\BenchmarkDotNet.IntegrationTests.SingleRuntime.DotNetFramework\BenchmarkDotNet.IntegrationTests.SingleRuntime.DotNetFramework.csproj' was resolved using '.NETFramework,Version=v4.6.2' instead of the project target framework '.NETCoreApp,Version=v8.0'. This project may not be fully compatible with your project. [C:\Projects\BenchmarkDotNet\tests\BenchmarkDotNet.IntegrationTests\bin\Release\net462\Job-VUALUD\BenchmarkDotNet.Autogenerated.csproj]";

            string expected = $@"The project which defines benchmarks does not target 'net8.0'." + Environment.NewLine +
                $"You need to add 'net8.0' to <TargetFrameworks> in your project file " +
                @"('C:\Projects\BenchmarkDotNet\tests\BenchmarkDotNet.IntegrationTests.SingleRuntime.DotNetFramework\BenchmarkDotNet.IntegrationTests.SingleRuntime.DotNetFramework.csproj')." + Environment.NewLine +
                "Example: <TargetFrameworks>net462;net8.0</TargetFrameworks>";
            Verify(msbuildError, true, expected);
        }

        [Fact]
        public void FutureDotNetVersionInMsBuildErrorIsTranslatedToMoreUserFriendlyVersion()
        {
            // A .NET version newer than any we would ever hardcode is still mapped to its short moniker.
            const string msbuildError = @"C:\...\Microsoft.Common.CurrentVersion.targets(1653,5): warning NU1702: ProjectReference 'C:\Projects\Benchmarks\Benchmarks.csproj' was resolved using '.NETFramework,Version=v4.6.2' instead of the project target framework '.NETCoreApp,Version=v12.0'. This project may not be fully compatible with your project. [C:\...\BenchmarkDotNet.Autogenerated.csproj]";

            string expected = "The project which defines benchmarks does not target 'net12.0'." + Environment.NewLine +
                "You need to add 'net12.0' to <TargetFrameworks> in your project file " +
                @"('C:\Projects\Benchmarks\Benchmarks.csproj')." + Environment.NewLine +
                "Example: <TargetFrameworks>net462;net12.0</TargetFrameworks>";

            Verify(msbuildError, true, expected);
        }

        [Fact]
        public void NotCompatibleMsBuildErrorIsTranslatedToMoreUserFriendlyVersion()
        {
            const string msbuildError = @"error NU1201: Project BenchmarkDotNet.IntegrationTests.SingleRuntime.DotNetCore is not compatible with net462 (.NETFramework,Version=v4.6.2) / win7-x64. Project BenchmarkDotNet.IntegrationTests.SingleRuntime.DotNetCore supports: net8.0 (.NETCoreApp,Version=v8.0)";

            string expected = $@"The project which defines benchmarks does not target 'net462'." + Environment.NewLine +
                $"You need to add 'net462' to <TargetFrameworks> in your project file " +
                @"('BenchmarkDotNet.IntegrationTests.SingleRuntime.DotNetCore')." + Environment.NewLine +
                "Example: <TargetFrameworks>net8.0;net462</TargetFrameworks>";

            Verify(msbuildError, true, expected);
        }

        [Fact]
        public void MissingSdkIsTranslatedToMoreUserFriendlyVersion()
        {
            const string msbuildError = @"C:\Program Files\dotnet\sdk\3.0.100-preview9-013617\Sdks\Microsoft.NET.Sdk\targets\Microsoft.NET.TargetFrameworkInference.targets(134,5): error NETSDK1045: The current .NET SDK does not support targeting .NET Core 5.0.  Either target .NET Core 3.0 or lower, or use a version of the .NET SDK that supports .NET Core 5.0. [C:\Projects\BenchmarkDotNet\samples\BenchmarkDotNet.Samples\bin\Release\net8.0\bad57fca-694a-41ad-b630-9e5317a782ab\BenchmarkDotNet.Autogenerated.csproj]";

            string expected = "The current .NET SDK does not support targeting .NET Core 5.0. You need to install it or pass the path to dotnet cli via the `--cli` console line argument.";

            Verify(msbuildError, true, expected);
        }

        [Fact]
        public void UnknownMSBuildErrorsAreNotTranslatedToMoreUserFriendlyVersions()
        {
            const string msbuildError = "warning NU1702: something is broken";

            Verify(msbuildError, false, null);
        }

        [Fact]
        public void MissingInProcessDiagnoserAssemblyReferenceIsTranslatedToMoreUserFriendlyVersion()
        {
            const string msbuildError = @"C:\...\ShortRun-1.notcs(157,125): error CS0234: The type or namespace name 'Diagnosers' does not exist in the namespace 'SomeCustom' (are you missing an assembly reference?) [C:\...\BenchmarkDotNet.Autogenerated.csproj]";

            string expected = "The in-process diagnoser handler 'FakeInProcessDiagnoserHandler' (from assembly 'BenchmarkDotNet.Tests') could not be found while building the benchmark." + Environment.NewLine +
                "In-process diagnoser handlers are compiled into the benchmark, so the project that defines your benchmarks must reference the assembly that contains the handler." + Environment.NewLine +
                "Add a reference to 'BenchmarkDotNet.Tests' in your benchmark project.";

            Verify(msbuildError, true, expected, typeof(SomeCustom.Diagnosers.FakeInProcessDiagnoserHandler));
        }

        [Fact]
        public void MissingBenchmarkDotNetReferenceIsTranslatedToMoreUserFriendlyVersion()
        {
            // Real error observed when the benchmark project doesn't flow a BenchmarkDotNet reference to the generated
            // benchmark: the generated code references Perfolizer (a BenchmarkDotNet dependency) and it can't be found.
            const string msbuildError = @"C:\...\Dry-1.notcs(10,20): error CS0400: The type or namespace name 'Perfolizer' could not be found in the global namespace (are you missing an assembly reference?) [C:\...\BenchmarkDotNet.Autogenerated.csproj]";

            string expected = "A BenchmarkDotNet (or BenchmarkDotNet dependency) type could not be found while building the benchmark: 'Perfolizer'." + Environment.NewLine +
                "The project that defines your benchmarks must reference BenchmarkDotNet.";

            Verify(msbuildError, true, expected);
        }

        [Fact]
        public void MissingValueTaskReferenceIsTranslatedToMoreUserFriendlyVersion()
        {
            // On .NET Framework, ValueTask comes from System.Threading.Tasks.Extensions (a BenchmarkDotNet dependency); if it
            // doesn't flow to the generated benchmark, the generated code fails to find System.Threading.Tasks.ValueTask.
            // Real error observed for the generic ValueTask<T> used by the generated code (the compiler reports 'ValueTask<>').
            const string msbuildError = @"C:\...\Job-ABC.notcs(1,1): error CS0234: The type or namespace name 'ValueTask<>' does not exist in the namespace 'System.Threading.Tasks' (are you missing an assembly reference?) [C:\...\BenchmarkDotNet.Autogenerated.csproj]";

            string expected = "A BenchmarkDotNet (or BenchmarkDotNet dependency) type could not be found while building the benchmark: 'System.Threading.Tasks.ValueTask'." + Environment.NewLine +
                "The project that defines your benchmarks must reference BenchmarkDotNet.";

            Verify(msbuildError, true, expected);
        }

        [AssertionMethod]
        private void Verify(string msbuildError, bool expectedResult, string? expectedReason, params Type[] inProcessDiagnoserHandlerTypes)
        {
            var sut = BuildResult.Failure(GenerateResult.Success(ArtifactsPaths.Empty, []), msbuildError);

            Assert.Equal(expectedResult, sut.TryToExplainFailureReason(inProcessDiagnoserHandlerTypes, out var reason));
            Assert.Equal(expectedReason, reason);
        }
    }
}

namespace SomeCustom.Diagnosers
{
    // Used by BuildResultTests to simulate an in-process diagnoser handler that lives in an assembly the benchmark
    // project doesn't reference.
    public sealed class FakeInProcessDiagnoserHandler { }
}
