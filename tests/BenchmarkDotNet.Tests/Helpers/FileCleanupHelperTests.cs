using AwesomeAssertions;
using BenchmarkDotNet.Helpers;

namespace BenchmarkDotNet.Tests.Helpers;

public class FileCleanupHelperTests : IDisposable
{
    private readonly string rootPath = Path.Combine(Path.GetTempPath(), $"BDN.FileCleanupHelperTests.{Guid.NewGuid():N}");

    public void Dispose()
    {
        if (!Directory.Exists(rootPath))
            return;

        foreach (var file in Directory.EnumerateFiles(rootPath, "*", SearchOption.AllDirectories))
            File.SetAttributes(file, FileAttributes.Normal);

        Directory.Delete(rootPath, recursive: true);
    }

    [Fact]
    public void CleanupRemovesFile()
    {
        var filePath = CreateFile(rootPath, "program.notcs");

        FileCleanupHelper.Cleanup(filePath);

        File.Exists(filePath).Should().BeFalse();
    }

    [Fact]
    public void CleanupRemovesReadOnlyFile()
    {
        var filePath = CreateFile(rootPath, "readonly.txt");
        File.SetAttributes(filePath, FileAttributes.ReadOnly);

        FileCleanupHelper.Cleanup(filePath);

        File.Exists(filePath).Should().BeFalse();
    }

    [Fact]
    public void CleanupRemovesDirectoryWithItsContents()
    {
        CreateFile(rootPath, "BenchmarkDotNet.Autogenerated.csproj");
        CreateFile(Path.Combine(rootPath, "obj"), "project.assets.json");
        CreateFile(Path.Combine(rootPath, "obj", "release_net10.0"), "program.dll");

        FileCleanupHelper.Cleanup(rootPath);

        Directory.Exists(rootPath).Should().BeFalse();
    }

    [Fact]
    public void CleanupRemovesDirectoryContainingReadOnlyFile()
    {
        File.SetAttributes(CreateFile(rootPath, "readonly.txt"), FileAttributes.ReadOnly);

        FileCleanupHelper.Cleanup(rootPath);

        Directory.Exists(rootPath).Should().BeFalse();
    }

    private static string CreateFile(string directoryPath, string fileName)
    {
        Directory.CreateDirectory(directoryPath);

        var filePath = Path.Combine(directoryPath, fileName);
        File.WriteAllText(filePath, "content");
        return filePath;
    }
}
