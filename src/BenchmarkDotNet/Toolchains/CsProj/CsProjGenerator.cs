    public class CsProjGenerator(DotNetCliSettings settings, bool isNetCore = true)
        : DotNetCliGenerator(settings, isNetCore)
    {
        private const string DefaultSdkName = "Microsoft.NET.Sdk";
        // The reference-gathering pass writes what it resolved beside the project, as a list and then as
        // the props file the real build imports.
        private const string GatherReferencesName = "BenchmarkDotNet.GatherReferences";
        internal const string AutogeneratedProjectName = "BenchmarkDotNet.Autogenerated.csproj";

        private static readonly ImmutableArray<string> SettingsWeWantToCopy =
        [
            "NetCoreAppImplicitPackageVersion",
            "RuntimeFrameworkVersion",
            "PackageTargetFallback",
            "LangVersion",
            "UseWpf",
            "UseWindowsForms",
            "CopyLocalLockFileAssemblies",
            "PreserveCompilationContext",
            "UserSecretsId",
            "EnablePreviewFeatures",
            "RuntimeHostConfigurationOption",
            "Features",

            "WarningsAsErrors",
            "WarningsNotAsErrors",
            "WarningLevel",
            "NoWarn",
            "MSBuildWarningsAsErrors",
            "MSBuildWarningsNotAsErrors",
            "MSBuildWarningsAsMessages",
            "SuppressTfmSupportBuildWarnings",

            "GarbageCollectionAdaptationMode", // TODO: Remove this setting after https://github.com/dotnet/runtime/pull/131069 issue is resolved, and backported to .NET 10.
        ];

        protected override string GetBuildArtifactsDirectoryPath(BuildPartition buildPartition, string programName)
        {
            string assemblyLocation = buildPartition.RepresentativeBenchmarkCase.Descriptor.Type.Assembly.Location;

            //Assemblies loaded from a stream will have an empty location (https://docs.microsoft.com/en-us/dotnet/api/system.reflection.assembly.location).
            string directoryName = assemblyLocation.IsEmpty() ?
                Path.Combine(Directory.GetCurrentDirectory(), "BenchmarkDotNet.Bin") :
                Path.GetDirectoryName(buildPartition.AssemblyLocation)!;

            return Path.Combine(directoryName, programName);
        }

        protected override string GetProjectFilePath(string buildArtifactsDirectoryPath)
            => Path.Combine(buildArtifactsDirectoryPath, AutogeneratedProjectName);

        protected override string GetBinariesDirectoryPath(string buildArtifactsDirectoryPath, string configuration)
            => Path.Combine(buildArtifactsDirectoryPath, "bin", configuration, Settings.TargetFrameworkMoniker);

        // Publishing has to land where BenchmarkDotNet looks for the executable, which is the binaries
        // directory: the toolchains that publish point that at their own publish folder already.
        protected override string GetPublishDirectoryPath(string buildArtifactsDirectoryPath, string configuration)
            => GetBinariesDirectoryPath(buildArtifactsDirectoryPath, configuration);

        /// <summary>
        /// Whether the toolchain publishes the project after building it, rather than only building it.
        /// </summary>
        protected virtual bool PublishesOutput => false;

        protected override ValueTask GenerateBuildScriptAsync(BuildPartition buildPartition, ArtifactsPaths artifactsPaths, CancellationToken cancellationToken)
        {
            var content = new StringBuilder(400);

            // The gathering pass builds whatever the toolchain does afterwards, so it is always a plain build.
            if (!buildPartition.ForcedNoDependenciesForIntegrationTests)
                AppendRestoreThenBuild(content, buildPartition, artifactsPaths, $"/p:{GatherReferencesProperty}=true");

            if (PublishesOutput)
                AppendPublish(content, buildPartition, artifactsPaths);
            else
                AppendBuild(content, buildPartition, artifactsPaths);

            return new(File.WriteAllTextAsync(artifactsPaths.BuildScriptFilePath, content.ToString(), cancellationToken));
        }

        /// <summary>
        /// Mirrors <see cref="DotNetCliCommand.RestoreThenBuildAsync"/>, which the gathering pass calls. That
        /// pass does not run when dependencies are skipped, so only its other two shapes can appear here.
        /// </summary>
        private void AppendRestoreThenBuild(StringBuilder content, BuildPartition buildPartition, ArtifactsPaths artifactsPaths, string? arguments)
        {
            string project = artifactsPaths.ProjectFilePath;
            string tfm = Settings.TargetFrameworkMoniker;

            if (buildPartition.IsCustomBuildConfiguration)
            {
                AppendCall(content, DotNetCliCommand.GetBuildCommand(artifactsPaths, buildPartition, project, tfm, arguments, "build"));
                return;
            }

            AppendCall(content, DotNetCliCommand.GetRestoreCommand(artifactsPaths, buildPartition, project, arguments, "restore"));
            AppendCall(content, DotNetCliCommand.GetBuildCommand(artifactsPaths, buildPartition, project, tfm, JoinArguments(arguments, "--no-restore"), "build-no-restore"));
        }

        /// <summary>
        /// Mirrors <see cref="DotNetCliCommand.BuildAsync"/>, which restores in the same invocation.
        /// </summary>
        private void AppendBuild(StringBuilder content, BuildPartition buildPartition, ArtifactsPaths artifactsPaths)
            => AppendCall(content, buildPartition.ForcedNoDependenciesForIntegrationTests
                ? DotNetCliCommand.GetBuildCommand(artifactsPaths, buildPartition, artifactsPaths.ProjectFilePath, Settings.TargetFrameworkMoniker, "--no-dependencies", "build-no-deps")
                : DotNetCliCommand.GetBuildCommand(artifactsPaths, buildPartition, artifactsPaths.ProjectFilePath, Settings.TargetFrameworkMoniker, null, "build"));

        /// <summary>
        /// Mirrors <see cref="DotNetCliCommand.PublishAsync"/>, which restores and builds in the same invocation.
        /// </summary>
        private void AppendPublish(StringBuilder content, BuildPartition buildPartition, ArtifactsPaths artifactsPaths)
            => AppendCall(content, buildPartition.ForcedNoDependenciesForIntegrationTests
                ? DotNetCliCommand.GetPublishCommand(artifactsPaths, buildPartition, artifactsPaths.ProjectFilePath, Settings.TargetFrameworkMoniker, "--no-dependencies", "publish-no-deps")
                : DotNetCliCommand.GetPublishCommand(artifactsPaths, buildPartition, artifactsPaths.ProjectFilePath, Settings.TargetFrameworkMoniker, null, "publish"));

        private void AppendCall(StringBuilder content, string command)
            => content.AppendLine($"call {Settings.CliPath?.FullName ?? DotNetCliCommandExecutor.DefaultDotNetCliPath.Value} {command}");

        private static string JoinArguments(params string?[] arguments)
            => string.Join(" ", arguments.Where(argument => argument.IsNotBlank()));

        protected override async ValueTask GenerateProjectAsync(BuildPartition buildPartition, ArtifactsPaths artifactsPaths, ILogger logger, CancellationToken cancellationToken)
        {
            await SaveProjectAsync(CreateProject(buildPartition, artifactsPaths, logger), artifactsPaths.ProjectFilePath, cancellationToken).ConfigureAwait(false);

            // Integration tests are built without dependencies, so we skip gathering dlls.
            if (buildPartition.ForcedNoDependenciesForIntegrationTests)
                return;

            await GatherReferencesAsync(buildPartition, artifactsPaths, logger, cancellationToken).ConfigureAwait(false);
        }

        protected static async ValueTask SaveProjectAsync(XDocument project, string path, CancellationToken cancellationToken)
        {
            using var stream = File.Create(path);
            await project.SaveAsync(stream, SaveOptions.None, cancellationToken).ConfigureAwait(false);
        }

        /// <summary>
        /// Builds the project handed to the SDK. It is composed rather than substituted into a template, so
        /// that a path holding an XML character cannot corrupt the file, and it is complete when written: the
        /// reference-gathering pass adds a file beside it rather than editing it.
        /// </summary>
        protected XDocument CreateProject(BuildPartition buildPartition, ArtifactsPaths artifactsPaths, ILogger logger)
        {
            var projectFile = GetProjectFilePath(buildPartition.RepresentativeBenchmarkCase.Descriptor.Type, logger);

            var xmlDoc = new XmlDocument();
            xmlDoc.Load(projectFile.FullName);
            var (customProperties, sdkName) = GetSettingsThatNeedToBeCopied(xmlDoc, projectFile);

            var project = new XElement("Project", new XAttribute("Sdk", GetSdkName(sdkName)));

            AddEarlyProperties(project, buildPartition, artifactsPaths, projectFile);
            AddProjectContent(project, buildPartition, artifactsPaths, projectFile);
            AddCopiedSettings(project, customProperties);
            AddLateProperties(project, buildPartition, artifactsPaths, projectFile);
            AddGatheredReferences(project);

            return new XDocument(project);
        }

        /// <summary>
        /// The SDK the generated project declares. It follows the benchmark project unless a toolchain needs
        /// a specific one.
        /// </summary>
        protected virtual string GetSdkName(string benchmarkProjectSdkName) => benchmarkProjectSdkName;

        /// <summary>
        /// Properties that must be in place before anything else reads them. Nothing later may decide where
        /// the output goes, because that is where BenchmarkDotNet looks for the executable.
        /// </summary>
        protected virtual void AddEarlyProperties(XElement project, BuildPartition buildPartition, ArtifactsPaths artifactsPaths, FileInfo projectFile)
            => project.Add(new XElement("PropertyGroup",
                // OutDir only falls back to OutputPath when unset, so a Directory.Build.props that sets
                // OutDir would otherwise keep it and send the build somewhere else.
                new XElement("OutDir", artifactsPaths.BinariesDirectoryPath),
                new XElement("OutputPath", artifactsPaths.BinariesDirectoryPath),
                new XElement("PublishDir", artifactsPaths.PublishDirectoryPath),
                // The path already ends with the moniker, so MSBuild must not append it again.
                new XElement("AppendTargetFrameworkToOutputPath", "false")));

        /// <summary>
        /// What the project builds, from which sources, and against which project.
        /// </summary>
        protected virtual void AddProjectContent(XElement project, BuildPartition buildPartition, ArtifactsPaths artifactsPaths, FileInfo projectFile)
        {
            project.Add(new XElement("PropertyGroup",
                new XElement("AssemblyTitle", artifactsPaths.ProgramName),
                new XElement("TargetFrameworks", Settings.TargetFrameworkMoniker),
                new XElement("AllowUnsafeBlocks", "true"),
                new XElement("PlatformTarget", buildPartition.Platform.ToConfig()),
                new XElement("AssemblyName", artifactsPaths.ProgramName),
                new XElement("OutputType", "Exe"),
                new XElement("TreatWarningsAsErrors", "False"),
                new XElement("MSBuildTreatWarningsAsErrors", "false"),
                new XComment(" disabled due to https://github.com/dotnet/roslyn/issues/59421 "),
                new XElement("DebugSymbols", "false"),
                new XElement("RunAnalyzers", "false"),
                new XComment(" fix for NETSDK1150: https://docs.microsoft.com/en-us/dotnet/core/compatibility/sdk/5.0/referencing-executable-generates-error "),
                new XElement("ValidateExecutableReferencesMatchSelfContained", "false"),
                new XElement("StartupObject", "BenchmarkDotNet.Autogenerated.UniqueProgramName")));

            AddCompileItems(project, artifactsPaths);

            project.Add(new XElement("ItemGroup",
                new XElement("ProjectReference", new XAttribute("Include", projectFile.FullName))));
        }

        /// <summary>
        /// The program to compile. The gathering pass builds this same file without running the compiler, so
        /// it does not matter that the references it needs are only resolvable once that pass has run.
        /// </summary>
        protected void AddCompileItems(XElement project, ArtifactsPaths artifactsPaths)
            => project.Add(new XElement("ItemGroup",
                new XElement("Compile", new XAttribute("Include", Path.GetFileName(artifactsPaths.ProgramCodePath)))));

        /// <summary>
        /// Settings copied from the benchmark project, parsed rather than pasted so whatever they hold stays
        /// inside its own elements.
        /// </summary>
        protected static void AddCopiedSettings(XElement project, string customProperties)
        {
            if (customProperties.IsBlank())
                return;

            project.Add(new XComment(" Begin copied settings from benchmarks project "));
            project.Add(ParseFragment(customProperties));
            project.Add(new XComment(" End copied settings "));
        }

        /// <summary>
        /// Properties that have to win over the copied settings, which is why they are added after them.
        /// </summary>
        protected virtual void AddLateProperties(XElement project, BuildPartition buildPartition, ArtifactsPaths artifactsPaths, FileInfo projectFile)
        {
            project.Add(new XComment(" LangVersion comes after the copied settings so it overrides one copied from the benchmarks project "));
            project.Add(new XElement("PropertyGroup",
                new XElement("LangVersion", new XAttribute("Condition", LangVersionCondition), "latest")));

            project.Add(ParseFragment(GetRuntimeSettings(buildPartition.RepresentativeBenchmarkCase.Job.Environment.Gc, buildPartition.Resolver)));
        }

        /// <summary>
        /// The gathering pass writes the references it resolved beside the project, and the real build imports
        /// them. Neither pass edits this file.
        /// </summary>
        protected void AddGatheredReferences(XElement project)
        {
            // The pass only needs what MSBuild resolves, so the compiler never runs and no executable is
            // produced. Without that it would write a program built against incomplete references into the
            // directory BenchmarkDotNet reads the benchmark executable from.
            project.Add(new XElement("PropertyGroup",
                new XAttribute("Condition", GatheringCondition),
                new XElement("SkipCompilerExecution", "true"),
                // Both of these copy a build product that no longer gets produced.
                new XElement("UseAppHost", "false"),
                new XElement("SkipCopyBuildProduct", "true")));

            project.Add(new XElement("Target",
                new XAttribute("Name", "BdnWriteReferences"),
                new XAttribute("Condition", GatheringCondition),
                new XAttribute("AfterTargets", "ResolveReferences"),
                new XElement("WriteLinesToFile",
                    new XAttribute("File", GatheredReferencesListName),
                    new XAttribute("Lines", ReferencePathTransform),
                    new XAttribute("Overwrite", "true"))));

            project.Add(new XElement("Import",
                new XAttribute("Project", GatheredReferencesPropsName),
                new XAttribute("Condition", $"{NotGatheringCondition} And Exists('{GatheredReferencesPropsName}')")));
        }

        private const string GatheringCondition = "'$(" + GatherReferencesProperty + ")' == 'true'";
        private const string NotGatheringCondition = "'$(" + GatherReferencesProperty + ")' != 'true'";
        private const string LangVersionCondition = "'$(LangVersion)' == '' Or ($([System.Char]::IsDigit('$(LangVersion)', 0)) And '$(LangVersion)' < '9.0')";
        private const string ReferencePathTransform = "@(ReferencePath->'%(FullPath)|%(FrameworkReferenceName)|%(FrameworkFile)|%(ResolvedFrom)')";
        private const string DesignTimeFacades = "ImplicitlyExpandDesignTimeFacades";
        private const string GatheredReferencesListName = "$(MSBuildThisFileDirectory)" + GatherReferencesName + ".txt";
        private const string GatheredReferencesPropsName = "$(MSBuildThisFileDirectory)" + GatherReferencesName + ".props";

        private static IEnumerable<XElement> ParseFragment(string xml)
            => xml.IsBlank() ? [] : XElement.Parse($"<Root>{xml}</Root>").Elements();

        private static IEnumerable<string> ReadGatheredReferences(ArtifactsPaths artifactsPaths)
        {
            var referencesFile = Path.Combine(artifactsPaths.BuildArtifactsDirectoryPath, $"{GatherReferencesName}.txt");
            if (!File.Exists(referencesFile))
                yield break;

            foreach (var line in File.ReadAllLines(referencesFile))
            {
                // <full path>|<framework reference it came from>|<is a framework reference assembly>|<what resolved it>
                var parts = line.Split('|');
                if (parts.Length < 4 || parts[0].Length == 0)
                    continue;

                // The framework's own assemblies are resolved by the generated project from its own
                // TargetFramework, so referencing them by path would pin the wrong ones. A targeting pack
                // names the framework reference it came from, .NET Framework marks its reference
                // assemblies, and the design-time facades name the target that expanded them, so between
                // them they identify one without matching against assembly or package names.
                if (parts[1].Length != 0
                    || parts[2].Equals("true", StringComparison.OrdinalIgnoreCase)
                    || parts[3].Equals(DesignTimeFacades, StringComparison.OrdinalIgnoreCase))
                    continue;

                yield return parts[0];
            }
        }

        private const string GatherReferencesProperty = "BenchmarkDotNetGatherReferences";

        /// <summary>
        /// Builds the project far enough for the SDK to resolve its references, then turns what it reported into a props file the real build imports.
        /// A ProjectReference alone does not put every referenced assembly in front of the compiler. #1197, #2344
        /// </summary>
        protected async ValueTask GatherReferencesAsync(BuildPartition buildPartition, ArtifactsPaths artifactsPaths, ILogger logger, CancellationToken cancellationToken)
        {
            BuildResult buildResult = await new DotNetCliCommand(
                Settings.CliPath,
                artifactsPaths.ProjectFilePath,
                Settings.TargetFrameworkMoniker,
                arguments: $"/p:{GatherReferencesProperty}=true",
                GenerateResult.Success(artifactsPaths, []),
                logger,
                buildPartition,
                [],
                buildPartition.Timeout
            )
                .RestoreThenBuildAsync(cancellationToken)
                .ConfigureAwait(false);

            if (!buildResult.IsBuildSuccess)
            {
                if (!buildResult.TryToExplainFailureReason(buildPartition.GetInProcessDiagnoserHandlerTypes(), out string? reason))
                {
                    reason = buildResult.ErrorMessage;
                }
                logger.WriteLineWarning($"Failed to gather assembly references, reason:{Environment.NewLine}{reason}");
                return;
            }

            var itemGroup = new XElement("ItemGroup");
            foreach (var assemblyFile in ReadGatheredReferences(artifactsPaths))
            {
                itemGroup.Add(new XElement("Reference",
                    new XAttribute("Include", Path.GetFileNameWithoutExtension(assemblyFile)),
                    new XElement("HintPath", assemblyFile)
                    // TODO: Add Aliases here for extern alias #2289
                ));
            }

            await SaveProjectAsync(
                new XDocument(new XElement("Project", itemGroup)),
                Path.Combine(artifactsPaths.BuildArtifactsDirectoryPath, $"{GatherReferencesName}.props"),
                cancellationToken).ConfigureAwait(false);
        }

        /// <summary>
        /// returns an MSBuild string that defines Runtime settings
        /// </summary>
        [PublicAPI]
        protected virtual string GetRuntimeSettings(GcMode gcMode, IResolver resolver)
        {
            var builder = new StringBuilder(80)
                .AppendLine($"<PropertyGroup>")
                .AppendLine($"    <ServerGarbageCollection>{gcMode.ResolveValue(GcMode.ServerCharacteristic, resolver).ToLowerCase()}</ServerGarbageCollection>")
                .AppendLine($"    <ConcurrentGarbageCollection>{gcMode.ResolveValue(GcMode.ConcurrentCharacteristic, resolver).ToLowerCase()}</ConcurrentGarbageCollection>");

            if (gcMode.HasValue(GcMode.RetainVmCharacteristic))
                builder.AppendLine($"    <RetainVMGarbageCollection>{gcMode.ResolveValue(GcMode.RetainVmCharacteristic, resolver).ToLowerCase()}</RetainVMGarbageCollection>");

            return builder.AppendLine("  </PropertyGroup>").ToString();
        }

        // the host project or one of the .props file that it imports might contain some custom settings that needs to be copied, sth like
        // <NetCoreAppImplicitPackageVersion>2.0.0-beta-001607-00</NetCoreAppImplicitPackageVersion>
        // <RuntimeFrameworkVersion>2.0.0-beta-001607-00</RuntimeFrameworkVersion>
        protected internal (string customProperties, string sdkName) GetSettingsThatNeedToBeCopied(XmlDocument xmlDoc, FileInfo projectFile)
        {
            XmlElement projectElement = xmlDoc.DocumentElement!;
            // custom SDKs are not added for non-netcoreapp apps (like net471), so when the TFM != netcoreapp we dont parse "<Import Sdk="
            // we don't allow for that mostly to prevent from edge cases like the following
            // <Import Sdk="Microsoft.NET.Sdk.WindowsDesktop" Project="Sdk.props" Condition="'$(TargetFramework)'=='netcoreapp3.0'"/>
            string? sdkName = null;
            if (Settings.TargetFrameworkMoniker.StartsWith("netcoreapp", StringComparison.InvariantCultureIgnoreCase))
            {
                foreach (XmlElement importElement in projectElement.GetElementsByTagName("Import"))
                {
                    sdkName = importElement.GetAttribute("Sdk");
                    if (sdkName.IsNotBlank())
                    {
                        break;
                    }
                }
            }
            if (sdkName.IsBlank())
            {
                sdkName = projectElement.GetAttribute("Sdk");
            }
            // If Sdk isn't an attribute on the Project element, it could be a child element.
            if (sdkName.IsBlank())
            {
                foreach (XmlElement sdkElement in projectElement.GetElementsByTagName("Sdk"))
                {
                    sdkName = sdkElement.GetAttribute("Name");
                    if (sdkName.IsBlank())
                    {
                        continue;
                    }
                    string version = sdkElement.GetAttribute("Version");
                    // Version is optional
                    if (version.IsNotBlank())
                    {
                        sdkName += $"/{version}";
                    }
                    break;
                }
            }
            if (sdkName.IsBlank())
            {
                sdkName = DefaultSdkName;
            }

            XmlDocument? itemGroupsettings = null;
            XmlDocument? propertyGroupSettings = null;

            GetSettingsThatNeedToBeCopied(projectElement, ref itemGroupsettings, ref propertyGroupSettings, projectFile);

            List<string> customSettings = new List<string>(2);
            if (itemGroupsettings != null)
            {
                customSettings.Add(GetIndentedXmlString(itemGroupsettings));
            }
            if (propertyGroupSettings != null)
            {
                customSettings.Add(GetIndentedXmlString(propertyGroupSettings));
            }

            return (string.Join(Environment.NewLine + Environment.NewLine, customSettings), sdkName);
        }

        private static void GetSettingsThatNeedToBeCopied(XmlElement projectElement, ref XmlDocument? itemGroupsettings, ref XmlDocument? propertyGroupSettings, FileInfo projectFile)
        {
            CopyProperties(projectElement, ref itemGroupsettings, "ItemGroup");
            CopyProperties(projectElement, ref propertyGroupSettings, "PropertyGroup");

            foreach (XmlElement importElement in projectElement.GetElementsByTagName("Import"))
            {
                string propsFilePath = importElement.GetAttribute("Project");
                var directoryName = projectFile.DirectoryName ?? throw new DirectoryNotFoundException(projectFile.DirectoryName);
                string absolutePath = File.Exists(propsFilePath)
                    ? propsFilePath // absolute path or relative to current dir
                    : Path.Combine(directoryName, propsFilePath); // relative to csproj
                if (File.Exists(absolutePath))
                {
                    var importXmlDoc = new XmlDocument();
                    importXmlDoc.Load(absolutePath);
                    GetSettingsThatNeedToBeCopied(importXmlDoc.DocumentElement!, ref itemGroupsettings, ref propertyGroupSettings, projectFile);
                }
            }
        }

        private static void CopyProperties(XmlElement projectElement, ref XmlDocument? copyToDocument, string groupName)
        {
            XmlElement? itemGroupElement = copyToDocument?.DocumentElement;
            foreach (XmlElement groupElement in projectElement.GetElementsByTagName(groupName))
            {
                foreach (var node in groupElement.ChildNodes)
                {
                    if (node is XmlElement setting && SettingsWeWantToCopy.Contains(setting.Name))
                    {
                        if (copyToDocument is null)
                        {
                            copyToDocument = new XmlDocument();
                            itemGroupElement = copyToDocument.CreateElement(groupName);
                            copyToDocument.AppendChild(itemGroupElement);
                        }
                        XmlNode copiedNode = copyToDocument.ImportNode(setting, true);
                        itemGroupElement!.AppendChild(copiedNode);
                    }
                }
            }
        }

        private static string GetIndentedXmlString(XmlDocument doc)
        {
            StringBuilder sb = new StringBuilder();
            XmlWriterSettings settings = new XmlWriterSettings
            {
                OmitXmlDeclaration = true,
                Indent = true,
                IndentChars = "  "
            };
            using (XmlWriter writer = XmlWriter.Create(sb, settings))
            {
                doc.Save(writer);
            }
            return sb.ToString();
        }

        /// <summary>
        /// returns a path to the project file which defines the benchmarks
        /// </summary>
        [PublicAPI]
        protected virtual FileInfo GetProjectFilePath(Type benchmarkTarget, ILogger logger)
        {
            if (!GetSolutionRootDirectory(out var rootDirectory) && !GetProjectRootDirectory(out rootDirectory))
            {
                logger.WriteLineError(
                    $"Unable to find .sln .slnx or .csproj file. Will use current directory {Directory.GetCurrentDirectory()} to search for project file. If you don't use .sln file on purpose it should not be a problem.");
                rootDirectory = new DirectoryInfo(Directory.GetCurrentDirectory());
            }

            // important assumption! project's file name === output dll name
            string projectName = benchmarkTarget.GetTypeInfo().Assembly.GetName().Name!;

            var projectFile = Helpers.FindProjectFile(rootDirectory, projectName);
            return projectFile;
        }
    }

    internal static class Helpers
    {
        private static readonly HashSet<string> IgnoredDirectoryNames = new(StringComparer.OrdinalIgnoreCase)
        {
            "bin",
            "obj",
        };

        private static readonly HashSet<string> ProjectExtensions = new(StringComparer.OrdinalIgnoreCase)
        {
            ".csproj",
            ".fsproj",
            ".vbproj"
        };

        private static bool ShouldIgnoreDirectory(DirectoryInfo directory)
            => IgnoredDirectoryNames.Contains(directory.Name)
            || directory.Name.StartsWith(".", StringComparison.Ordinal)
#if NETSTANDARD2_0
            || directory.Attributes.HasFlag(FileAttributes.Hidden)
            || directory.Attributes.HasFlag(FileAttributes.ReparsePoint)
#endif
            ;

        public static FileInfo FindProjectFile(DirectoryInfo rootDirectory, string projectName)
        {
            var projectFiles = EnumerateProjectFiles(rootDirectory, projectName);

            // Take first 2 items for performance reasons
            var files = projectFiles.Take(2).ToArray();
            return files.Length switch
            {
                1 => files[0],
                0 => throw new NotSupportedException(
                    $"Unable to find {projectName} in {rootDirectory.FullName} and its subfolders. Most probably the name of output exe is different than the name of the .(c/f)sproj"),
                _ => throw new NotSupportedException(
                    $"Found more than one matching project file for {projectName} in {rootDirectory.FullName} and its subfolders: '{files[0].FullName}','{files[1].FullName}'. Benchmark project names needs to be unique."),
            };
        }

        private static IEnumerable<FileInfo> EnumerateProjectFiles(DirectoryInfo rootDirectory, string projectName)
        {
            var stack = new Stack<DirectoryInfo>();
            stack.Push(rootDirectory);

            while (stack.Count > 0)
            {
                var currentDir = stack.Pop();

                // 1. Search '*.proj' files in the current directory
                IEnumerable<FileInfo> files = EnumerateProjectFiles(currentDir);

                foreach (var file in files)
                {
                    if (!ProjectExtensions.Contains(file.Extension))
                        continue;

                    if (Path.GetFileNameWithoutExtension(file.Name) == projectName)
                        yield return file;
                }

                var subDirectories = GetSubDirectories(currentDir);

                // 2. Handle sub directories.
                foreach (var dir in subDirectories)
                {
                    if (ShouldIgnoreDirectory(dir))
                        continue;
                    stack.Push(dir);
                }
            }
        }

#if NETSTANDARD2_0
        private static IEnumerable<FileInfo> EnumerateProjectFiles(DirectoryInfo directory)
        {
            IEnumerable<FileInfo> projectFiles;
            try
            {
                projectFiles = directory.EnumerateFiles("*proj", SearchOption.TopDirectoryOnly);
            }
            catch
            {
                yield break;
            }

            foreach (var file in projectFiles)
                yield return file;
        }

        private static IEnumerable<DirectoryInfo> GetSubDirectories(DirectoryInfo currentDir)
        {
            try
            {
                return currentDir.EnumerateDirectories();
            }
            catch
            {
                return [];
            }
        }
#else
        private static readonly EnumerationOptions DirectoryEnumerationOptions = new()
        {
            RecurseSubdirectories = false,
            IgnoreInaccessible = true,
            AttributesToSkip = FileAttributes.ReparsePoint | FileAttributes.Hidden
        };

        private static IEnumerable<FileInfo> EnumerateProjectFiles(DirectoryInfo directory)
            => directory.EnumerateFiles("*proj", DirectoryEnumerationOptions);

        private static IEnumerable<DirectoryInfo> GetSubDirectories(DirectoryInfo currentDir)
            => currentDir.EnumerateDirectories("*", DirectoryEnumerationOptions);
#endif
    }
