
namespace BenchmarkDotNet.Code;

// Member names emitted by the code generator onto the generated runnable type - used by both the out-of-process
// template (Templates/BenchmarkType.txt via CodeGenerator/DeclarationsProvider) and the in-process IL emitter
// (RunnableEmitter).
internal class RunnableConstants
{
    public const string EmittedTypePrefix = "BenchmarkDotNet.Autogenerated.Runnable_";
    // Run lives on its own type so that the names it binds resolve outside the runnable, where the
    // runnable's private members cannot hide the benchmark members they are named after.
    public const string RunnerTypePrefix = "BenchmarkDotNet.Autogenerated.Runner_";
    public const string ArgFieldPrefix = "argField";
    public const string ArgParamPrefix = "arg";

    public const string InvokeCountParamName = "invokeCount";
    public const string ClockParamName = "clock";

    public const string RunMethodName = "Run";
    // A namespace-level type rather than a member of the runnable: nested, it would be a member visible to Runner_<id>,
    // and so would shadow a benchmark member of the same name in the object initializer.
    public const string FieldsContainerTypePrefix = "BenchmarkDotNet.Autogenerated.FieldsContainer_";

    // A delegate returning a reference to the fields container, so Runner_<id> can assign the argument fields without
    // the runnable having to expose the field. Declared next to the container, and non-generic, so it adds no public API.
    public const string FieldsRefTypePrefix = "BenchmarkDotNet.Autogenerated.FieldsRef_";
    public const string FieldsContainerGetterName = "GetFieldsContainer";
    public const string FieldsContainerName = "fieldsContainer";
    public const string WorkloadValueTaskSourceFieldName = "workloadValueTaskSource";
    public const string ClockFieldName = "clock";
    public const string InvokeCountFieldName = "invokeCount";

    public const string TrickTheJitCoreMethodName = "TrickTheJIT";
    public const string ForDisassemblyDiagnoserMethodName = "ForDisassemblyDiagnoser";
    public const string GlobalSetupMethodName = "GlobalSetup";
    public const string GlobalCleanupMethodName = "GlobalCleanup";
    public const string IterationSetupMethodName = "IterationSetup";
    public const string IterationCleanupMethodName = "IterationCleanup";
    public const string OverheadImplementationMethodName = "Overhead";
    public const string OverheadActionUnrollMethodName = "OverheadActionUnroll";
    public const string OverheadActionNoUnrollMethodName = "OverheadActionNoUnroll";
    public const string WorkloadActionUnrollMethodName = "WorkloadActionUnroll";
    public const string WorkloadActionNoUnrollMethodName = "WorkloadActionNoUnroll";
    public const string StartWorkloadMethodName = "StartWorkload";
    public const string WorkloadCoreMethodName = "WorkloadCore";

}
